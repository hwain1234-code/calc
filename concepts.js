const CR=(a,b)=>Math.floor(Math.random()*(b-a+1))+a;
const cpick=a=>a[Math.floor(Math.random()*a.length)];
const cshuffle=a=>{a=a.slice();for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}return a;};
const N=v=>{ // 숫자 표시: 1234.5 → 1,234.5
  if(typeof v!=='number')return v;
  const r=Math.round(v*100)/100;
  return r.toLocaleString('ko-KR',{maximumFractionDigits:2});
};
const Nd=v=>typeof dec==='function'?dec(N(v)):N(v); // 소수점 강조 포함
// 표 HTML (설명·intro용)
function htable(head,rows){
  return `<table class="ctab"><tr>${head.map(h=>`<th>${h}</th>`).join('')}</tr>${rows.map(r=>`<tr>${r.map((c,i)=>i===0?`<th class="rl">${c}</th>`:`<td>${c}</td>`).join('')}</tr>`).join('')}</table>`;
}
const F=(a,b)=>`<span class="frac"><span class="n">${a}</span><span class="d">${b}</span></span>`; // 분수 표시
const box=(t,b)=>`<div class="exb"><div class="exh">${t}</div>${b}</div>`;

/* ---------- 공통: 비율 쌍에서 보여줄 칸 고르기 ---------- */
// keys 중 n개를 보여주고 나머지는 빈칸
const showSome=(keys,n)=>{const s=new Set(cshuffle(keys).slice(0,n));return k=>s.has(k);};

